   "x": "When a new patient first enters a doctor’s office, they are presented with paperwork- the intake form. The intake form serves a dual purpose: “to give the clinician relevant information, required in their role of promoting patient wellbeing” (Dahlen, 2020, p.46) and to garner information for insurance purposes (Hagen & Galupo, 2014, p.25). A prerequisite question that is asked to answer both needs is natal sex, or sex assigned at birth, often referred to in forms either as “sex” or “gender,” often conflating the two terms (Pye & Goins, 2013, p. 402). However, the intake form can serve a third purpose, to include or discriminate. For nonbinary patients who do not identify as either “male” or “female,” the healthcare experience is already fraught. A significant number of transgender individuals have experienced harassment, discrimination and violence in healthcare settings (Grant et. al, 2010, pp.5-6). But even when there is not intentional harassment, discrimination, and violence, the “male or female” question represents a hegemonic gender binary worldview enshrined in institutional language and rooted in medicalism. It is an often overlooked piece of health communication that can lead to dysphoric and uncomfortable experiences for nonbinary patients (Pye & Goins, 2013, pp. 402-403). If a healthcare provider reads an intake form that only let the patient provide their natal sex and legal name, the provider might then assume the patient is cisgender and then go on to misgender– the term for using “the wrong pronouns or other gender-specific words when referring to or speaking to someone, especially a transgender person” (Meaning of misgender in English, Cambridge Dictionary)– the patient throughout the interaction, causing distress. The intake form can be analyzed for signs of whether an institution has had these discussions or whether it remains rooted in exclusionary and binary gender worldviews (Pye & Goins, 2013, p. 399)."
